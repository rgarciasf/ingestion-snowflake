// Builds snowflake/07_knowledge_graph.sql: Ingestion's knowledge graph (data/graph.json) plus the facts added
// for this project (data/graph-additions.json), as entity and relation tables in ACME.KNOWLEDGE.
// Usage: node scripts/build-graph-sql.mjs
import { readFileSync, writeFileSync } from "node:fs";

const ROOT = new URL("..", import.meta.url).pathname;
const base = JSON.parse(readFileSync(`${ROOT}data/graph.json`, "utf8"));
const extra = JSON.parse(readFileSync(`${ROOT}data/graph-additions.json`, "utf8"));

// Later sources enrich earlier ones (description, aliases) instead of duplicating entities.
const entities = new Map();
for (const [source, list] of [["ingestion", base.entities], ["hackathon", extra.entities]]) {
  for (const e of list) {
    const prev = entities.get(e.name);
    entities.set(e.name, {
      name: e.name,
      type: e.type ?? prev?.type,
      aliases: [...new Set([...(prev?.aliases ?? []), ...(e.aliases ?? [])])],
      description: e.description ?? prev?.description ?? null,
      source: prev?.source ?? source,
    });
  }
}
const relations = [
  ...base.relations.map((r) => ({ ...r, source: "ingestion" })),
  ...extra.relations.map((r) => ({ ...r, source: "hackathon" })),
];
for (const r of relations) {
  for (const n of [r.from, r.to]) if (!entities.has(n)) throw new Error(`Relation references unknown entity: ${n}`);
}

const q = (v) => (v === null || v === undefined || v === "" ? "NULL" : `'${String(v).replace(/'/g, "''")}'`);

const sql = `-- GENERATED by scripts/build-graph-sql.mjs from data/graph.json (Ingestion) + data/graph-additions.json. Do not edit.
-- ${entities.size} entities, ${relations.length} relations. Shared company knowledge for both versions.
USE ROLE ACCOUNTADMIN;
USE WAREHOUSE ACME_WH;
USE SCHEMA ACME.KNOWLEDGE;

CREATE OR REPLACE TABLE KG_ENTITIES (
  NAME STRING, TYPE STRING COMMENT 'TEAM, PERSON, SERVICE, DATASTORE, FEATURE, INCIDENT, TOOL, VENDOR, CUSTOMER',
  ALIASES ARRAY, DESCRIPTION STRING, SOURCE STRING COMMENT 'ingestion (original graph) or hackathon (added)'
) COMMENT = 'Knowledge graph nodes: teams, people, services, incidents, customers';
INSERT INTO KG_ENTITIES
SELECT column1, column2, IFF(column3 IS NULL, ARRAY_CONSTRUCT(), SPLIT(column3, '|')), column4, column5 FROM VALUES
${[...entities.values()].map((e) => `(${[e.name, e.type, e.aliases.join("|").toLowerCase(), e.description, e.source].map(q).join(", ")})`).join(",\n")};

CREATE OR REPLACE TABLE KG_RELATIONS (
  FROM_ENTITY STRING, PREDICATE STRING COMMENT 'OWNED_BY, DEPENDS_ON, MEMBER_OF, LEADS, KEY_PERSON_FOR, MANAGES_ACCOUNT, AFFECTED, USES, ...',
  TO_ENTITY STRING, CONTEXT STRING, SOURCE STRING
) COMMENT = 'Knowledge graph edges (directed, typed)';
INSERT INTO KG_RELATIONS VALUES
${relations.map((r) => `(${[r.from, r.predicate, r.to, r.context, r.source].map(q).join(", ")})`).join(",\n")};

-- Readable by the Revenue personas (the HR personas get it in hr/13_hr_governance.sql).
GRANT SELECT ON TABLE KG_ENTITIES TO ROLE ACME_CS_LEAD;
GRANT SELECT ON TABLE KG_ENTITIES TO ROLE ACME_CSM_EU;
GRANT SELECT ON TABLE KG_RELATIONS TO ROLE ACME_CS_LEAD;
GRANT SELECT ON TABLE KG_RELATIONS TO ROLE ACME_CSM_EU;

-- Example: everything within 2 hops of Lena Okafor (both directions).
WITH RECURSIVE edges AS (
  SELECT FROM_ENTITY AS src, TO_ENTITY AS dst, FROM_ENTITY, PREDICATE, TO_ENTITY FROM KG_RELATIONS
  UNION ALL
  SELECT TO_ENTITY, FROM_ENTITY, FROM_ENTITY, PREDICATE, TO_ENTITY FROM KG_RELATIONS
), walk AS (
  SELECT 'Lena Okafor' AS node, 0 AS hop, NULL AS f, NULL AS p, NULL AS t, ARRAY_CONSTRUCT('Lena Okafor') AS seen
  UNION ALL
  SELECT e.dst, w.hop + 1, e.FROM_ENTITY, e.PREDICATE, e.TO_ENTITY, ARRAY_APPEND(w.seen, e.dst)
  FROM walk w JOIN edges e ON e.src = w.node
  WHERE w.hop < 2 AND NOT ARRAY_CONTAINS(e.dst::VARIANT, w.seen)
)
SELECT DISTINCT hop, f AS from_entity, p AS predicate, t AS to_entity FROM walk WHERE hop > 0 ORDER BY hop, from_entity;
`;
writeFileSync(`${ROOT}snowflake/07_knowledge_graph.sql`, sql);
console.log(`Wrote snowflake/07_knowledge_graph.sql: ${entities.size} entities, ${relations.length} relations`);
