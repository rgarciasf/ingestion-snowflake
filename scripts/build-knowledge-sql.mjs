// Builds snowflake/03_knowledge.sql from data/sources/**: one DOCUMENTS row per file and
// DOC_CHUNKS rows sized for Cortex Search (transcripts by time window, docs by heading, JSON by item).
// Usage: node scripts/build-knowledge-sql.mjs
import { readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { join, relative, basename, extname } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
const SRC = join(ROOT, "data/sources");
const OUT = join(ROOT, "snowflake/03_knowledge.sql");
const LINES_PER_TRANSCRIPT_CHUNK = 5;

const walk = (dir) =>
  readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });

function parseFrontmatter(text) {
  const m = text.match(/^---\n([\s\S]*?)\n---\n?/);
  if (!m) return { meta: {}, body: text };
  const meta = Object.fromEntries(
    m[1].split("\n").map((l) => l.match(/^(\w+):\s*(.*)$/)).filter(Boolean).map((x) => [x[1], x[2].trim()]),
  );
  return { meta, body: text.slice(m[0].length) };
}

function chunkMarkdown(title, body) {
  const lines = body.split("\n");
  const transcript = lines.filter((l) => /^\[\d\d:\d\d:\d\d\]/.test(l));
  const chunks = [];
  if (transcript.length) {
    // Header (attendees etc.) is its own chunk; then fixed windows of transcript lines.
    const header = lines.filter((l) => !/^\[\d\d:\d\d:\d\d\]/.test(l)).join("\n").trim();
    if (header) chunks.push({ text: `${title}\n\n${header}`, ts: null });
    for (let i = 0; i < transcript.length; i += LINES_PER_TRANSCRIPT_CHUNK) {
      const win = transcript.slice(i, i + LINES_PER_TRANSCRIPT_CHUNK);
      const from = win[0].slice(1, 9);
      const to = win[win.length - 1].slice(1, 9);
      chunks.push({ text: `${title} - Transcript ${from}-${to}\n\n${win.join("\n")}`, ts: from });
    }
    return chunks;
  }
  // Split on level-2 headings; keep the H1 intro with the first section.
  let current = [];
  let heading = "";
  const flush = () => {
    const t = current.join("\n").trim();
    if (t) chunks.push({ text: `${title}${heading ? ` - ${heading}` : ""}\n\n${t}`, ts: null });
    current = [];
  };
  for (const l of lines) {
    if (l.startsWith("## ")) {
      flush();
      heading = l.slice(3).trim();
    } else current.push(l);
  }
  flush();
  return chunks;
}

function chunkJson(title, items) {
  return items.map((item) => ({
    text: `${title}\n\n${Object.entries(item).map(([k, v]) => `${k}: ${typeof v === "string" ? v : JSON.stringify(v)}`).join("\n")}`,
    ts: null,
    account: typeof item.customer === "string" ? item.customer.replace(/\s*\(.*\)$/, "") : null,
  }));
}

const sqlStr = (v) => {
  if (v === null || v === undefined || v === "") return "NULL";
  if (String(v).includes("$$")) throw new Error("content contains $$");
  return `$$${v}$$`;
};

const docs = [];
const chunks = [];
for (const file of walk(SRC).sort()) {
  const ext = extname(file);
  if (![".md", ".json"].includes(ext)) continue;
  const rel = relative(SRC, file);
  const sourceType = rel.split("/")[0];
  const docId = rel.replace(/\.(md|json)$/, "").replace(/[^a-z0-9]+/gi, "-").toLowerCase();
  const raw = readFileSync(file, "utf8");
  let meta = {};
  let body = raw;
  let fileChunks;
  if (ext === ".md") {
    ({ meta, body } = parseFrontmatter(raw));
    fileChunks = chunkMarkdown(meta.title ?? basename(file), body);
  } else {
    const parsed = JSON.parse(raw);
    const title = parsed.title ?? basename(file, ext).replace(/-/g, " ").replace(/\b\w/g, (c) => c.toUpperCase());
    // A JSON array is one chunk per item; a single object is one chunk.
    meta = Array.isArray(parsed) ? { title } : { title, updated: parsed.updated, owner: parsed.owner };
    fileChunks = chunkJson(title, Array.isArray(parsed) ? parsed : [parsed]);
  }
  const updated = meta.updated ?? (rel.match(/(\d{4}-\d{2}-\d{2})/) || [])[1] ?? null;
  docs.push({
    docId, title: meta.title, sourceType, owner: meta.owner, updated, access: meta.access ?? "all",
    status: meta.status ?? "current", account: meta.account, team: meta.team, path: rel, content: body.trim(),
  });
  fileChunks.forEach((c, i) =>
    chunks.push({
      chunkId: `${docId}--${i}`, docId, i, title: meta.title, sourceType, access: meta.access ?? "all",
      status: meta.status ?? "current", account: c.account ?? meta.account, team: meta.team, updated, ts: c.ts, text: c.text,
    }),
  );
}

const out = [];
out.push(`-- GENERATED by scripts/build-knowledge-sql.mjs from data/sources/** (${docs.length} documents, ${chunks.length} chunks). Do not edit.
USE WAREHOUSE ACME_WH;
USE SCHEMA ACME.KNOWLEDGE;

CREATE OR REPLACE TABLE DOCUMENTS (
  DOC_ID STRING, TITLE STRING, SOURCE_TYPE STRING COMMENT 'docs, faqs, meetings, policies, product, support, tools',
  OWNER STRING, UPDATED_ON DATE, ACCESS STRING COMMENT 'all, managers or hr (enforced by row access policy)',
  STATUS STRING COMMENT 'current or superseded (superseded documents lose to current ones)',
  ACCOUNT STRING COMMENT 'Customer account the document is about (meetings, tickets)',
  TEAM STRING COMMENT 'Acme team the document is about (HR version)', PATH STRING, CONTENT STRING
) COMMENT = 'Acme company knowledge: one row per source document';

CREATE OR REPLACE TABLE DOC_CHUNKS (
  CHUNK_ID STRING, DOC_ID STRING, CHUNK_INDEX NUMBER, TITLE STRING, SOURCE_TYPE STRING, ACCESS STRING, STATUS STRING,
  ACCOUNT STRING, TEAM STRING, UPDATED_ON DATE, TRANSCRIPT_TS STRING COMMENT 'hh:mm:ss where this transcript window starts', CHUNK_TEXT STRING
) COMMENT = 'Search-sized chunks of DOCUMENTS, indexed by the KNOWLEDGE_SEARCH Cortex Search service';
`);
out.push("INSERT INTO DOCUMENTS VALUES");
out.push(docs.map((d) => `(${[d.docId, d.title, d.sourceType, d.owner, d.updated, d.access, d.status, d.account, d.team, d.path, d.content].map(sqlStr).join(", ")})`).join(",\n") + ";\n");
out.push("INSERT INTO DOC_CHUNKS VALUES");
out.push(chunks.map((c) => `(${[c.chunkId, c.docId].map(sqlStr).join(", ")}, ${c.i}, ${[c.title, c.sourceType, c.access, c.status, c.account, c.team, c.updated, c.ts, c.text].map(sqlStr).join(", ")})`).join(",\n") + ";\n");
out.push("SELECT SOURCE_TYPE, COUNT(*) AS chunks FROM DOC_CHUNKS GROUP BY 1 ORDER BY 1;\n");
writeFileSync(OUT, out.join("\n"));
console.log(`Wrote ${relative(ROOT, OUT)}: ${docs.length} documents, ${chunks.length} chunks`);
