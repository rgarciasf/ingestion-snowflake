-- 05_governance.sql: personas as Snowflake roles, enforced by the database (not by the app).
--   ACME_CS_LEAD : VP Customer Success. Sees every account and manager-only documents.
--   ACME_CSM_EU  : EU Customer Success Manager. Sees only eu-central accounts (row access policy).
-- The agent runs every query with the persona's role, so the same question returns different, governed answers.

USE ROLE ACCOUNTADMIN;
USE WAREHOUSE ACME_WH;

CREATE ROLE IF NOT EXISTS ACME_CS_LEAD COMMENT = 'Persona: VP Customer Success (all accounts)';
CREATE ROLE IF NOT EXISTS ACME_CSM_EU  COMMENT = 'Persona: EU Customer Success Manager (eu-central accounts only)';

CREATE SCHEMA IF NOT EXISTS ACME.GOVERNANCE COMMENT = 'Policies and entitlement tables. Not granted to personas.';

-- Re-runnable: detach existing policies before they are replaced below.
ALTER TABLE IF EXISTS ACME.PULSE.WORKSPACES      DROP ALL ROW ACCESS POLICIES;
ALTER TABLE IF EXISTS ACME.PULSE.EVENTS          DROP ALL ROW ACCESS POLICIES;
ALTER TABLE IF EXISTS ACME.PULSE.INVOICES        DROP ALL ROW ACCESS POLICIES;
ALTER TABLE IF EXISTS ACME.PULSE.SUPPORT_TICKETS DROP ALL ROW ACCESS POLICIES;
ALTER TABLE IF EXISTS ACME.BRAIN.COMMITMENTS     DROP ALL ROW ACCESS POLICIES;
ALTER TABLE IF EXISTS ACME.BRAIN.RISK_ALERTS     DROP ALL ROW ACCESS POLICIES;
ALTER TABLE IF EXISTS ACME.KNOWLEDGE.DOCUMENTS   DROP ALL ROW ACCESS POLICIES;
ALTER TABLE IF EXISTS ACME.KNOWLEDGE.DOC_CHUNKS  DROP ALL ROW ACCESS POLICIES;
ALTER TABLE IF EXISTS ACME.PULSE.AI_SUBSCRIPTIONS     DROP ALL ROW ACCESS POLICIES;   -- re-attached by 08
ALTER TABLE IF EXISTS ACME.PULSE.AI_TOKEN_USAGE_DAILY DROP ALL ROW ACCESS POLICIES;

-- Entitlements: which role may see which region.
CREATE OR REPLACE TABLE ACME.GOVERNANCE.REGION_ENTITLEMENTS (ROLE_NAME STRING, REGION STRING);
INSERT INTO ACME.GOVERNANCE.REGION_ENTITLEMENTS VALUES
  ('ACME_CS_LEAD', 'us-east'), ('ACME_CS_LEAD', 'eu-central'),
  ('ACME_CSM_EU', 'eu-central');

-- Workspace -> region lookup used by the policy (a plain table, so the policy never recurses into WORKSPACES).
CREATE OR REPLACE TABLE ACME.GOVERNANCE.WORKSPACE_REGION AS
  SELECT WORKSPACE_ID, REGION FROM ACME.PULSE.WORKSPACES;

-- One policy for every table keyed by WORKSPACE_ID.
CREATE OR REPLACE ROW ACCESS POLICY ACME.GOVERNANCE.ACCOUNT_REGION_POLICY
  AS (ws_id NUMBER) RETURNS BOOLEAN ->
    IS_ROLE_IN_SESSION('ACCOUNTADMIN')
    OR EXISTS (
      SELECT 1
      FROM ACME.GOVERNANCE.WORKSPACE_REGION r
      JOIN ACME.GOVERNANCE.REGION_ENTITLEMENTS e ON e.REGION = r.REGION
      WHERE r.WORKSPACE_ID = ws_id AND IS_ROLE_IN_SESSION(e.ROLE_NAME)
    )
  COMMENT = 'Customer data is visible only to roles entitled to the customer''s data-residency region';

ALTER TABLE ACME.PULSE.WORKSPACES      ADD ROW ACCESS POLICY ACME.GOVERNANCE.ACCOUNT_REGION_POLICY ON (WORKSPACE_ID);
ALTER TABLE ACME.PULSE.EVENTS          ADD ROW ACCESS POLICY ACME.GOVERNANCE.ACCOUNT_REGION_POLICY ON (WORKSPACE_ID);
ALTER TABLE ACME.PULSE.INVOICES        ADD ROW ACCESS POLICY ACME.GOVERNANCE.ACCOUNT_REGION_POLICY ON (WORKSPACE_ID);
ALTER TABLE ACME.PULSE.SUPPORT_TICKETS ADD ROW ACCESS POLICY ACME.GOVERNANCE.ACCOUNT_REGION_POLICY ON (WORKSPACE_ID);
ALTER TABLE ACME.BRAIN.COMMITMENTS     ADD ROW ACCESS POLICY ACME.GOVERNANCE.ACCOUNT_REGION_POLICY ON (WORKSPACE_ID);
ALTER TABLE ACME.BRAIN.RISK_ALERTS     ADD ROW ACCESS POLICY ACME.GOVERNANCE.ACCOUNT_REGION_POLICY ON (WORKSPACE_ID);

-- Manager-only documents (e.g. compensation bands) are hidden from non-leads.
CREATE OR REPLACE ROW ACCESS POLICY ACME.GOVERNANCE.DOC_ACCESS_POLICY
  AS (access STRING) RETURNS BOOLEAN ->
    access = 'all' OR IS_ROLE_IN_SESSION('ACME_CS_LEAD') OR IS_ROLE_IN_SESSION('ACCOUNTADMIN')
  COMMENT = 'Documents with access = managers are visible to leads only';
ALTER TABLE ACME.KNOWLEDGE.DOCUMENTS ADD ROW ACCESS POLICY ACME.GOVERNANCE.DOC_ACCESS_POLICY ON (ACCESS);
-- Chunks too, so a citation or direct SQL can't read a protected document. (Cortex Search runs with owner's rights;
-- the app filters search results by the persona's access levels, see searchKnowledge in src/agent.ts.)
ALTER TABLE ACME.KNOWLEDGE.DOC_CHUNKS ADD ROW ACCESS POLICY ACME.GOVERNANCE.DOC_ACCESS_POLICY ON (ACCESS);

-- Grants (same for both personas; the policies do the filtering).
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE ACME_CS_LEAD;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE ACME_CSM_EU;

GRANT USAGE ON WAREHOUSE ACME_WH TO ROLE ACME_CS_LEAD;
GRANT USAGE ON WAREHOUSE ACME_WH TO ROLE ACME_CSM_EU;
GRANT USAGE ON DATABASE ACME TO ROLE ACME_CS_LEAD;
GRANT USAGE ON DATABASE ACME TO ROLE ACME_CSM_EU;

GRANT USAGE ON SCHEMA ACME.PULSE TO ROLE ACME_CS_LEAD;
GRANT USAGE ON SCHEMA ACME.PULSE TO ROLE ACME_CSM_EU;
GRANT USAGE ON SCHEMA ACME.KNOWLEDGE TO ROLE ACME_CS_LEAD;
GRANT USAGE ON SCHEMA ACME.KNOWLEDGE TO ROLE ACME_CSM_EU;
GRANT USAGE ON SCHEMA ACME.BRAIN TO ROLE ACME_CS_LEAD;
GRANT USAGE ON SCHEMA ACME.BRAIN TO ROLE ACME_CSM_EU;

GRANT SELECT ON ALL TABLES IN SCHEMA ACME.PULSE TO ROLE ACME_CS_LEAD;
GRANT SELECT ON ALL TABLES IN SCHEMA ACME.PULSE TO ROLE ACME_CSM_EU;
GRANT SELECT ON ALL VIEWS IN SCHEMA ACME.PULSE TO ROLE ACME_CS_LEAD;
GRANT SELECT ON ALL VIEWS IN SCHEMA ACME.PULSE TO ROLE ACME_CSM_EU;
GRANT SELECT ON SEMANTIC VIEW ACME.PULSE.PULSE_ANALYTICS TO ROLE ACME_CS_LEAD;
GRANT SELECT ON SEMANTIC VIEW ACME.PULSE.PULSE_ANALYTICS TO ROLE ACME_CSM_EU;
REVOKE SELECT ON TABLE ACME.PULSE.STORY_ACCOUNTS FROM ROLE ACME_CS_LEAD;   -- seed input, not company data
REVOKE SELECT ON TABLE ACME.PULSE.STORY_ACCOUNTS FROM ROLE ACME_CSM_EU;

GRANT SELECT ON ALL TABLES IN SCHEMA ACME.KNOWLEDGE TO ROLE ACME_CS_LEAD;
GRANT SELECT ON ALL TABLES IN SCHEMA ACME.KNOWLEDGE TO ROLE ACME_CSM_EU;
GRANT USAGE ON CORTEX SEARCH SERVICE ACME.KNOWLEDGE.KNOWLEDGE_SEARCH TO ROLE ACME_CS_LEAD;
GRANT USAGE ON CORTEX SEARCH SERVICE ACME.KNOWLEDGE.KNOWLEDGE_SEARCH TO ROLE ACME_CSM_EU;

GRANT SELECT, INSERT ON ALL TABLES IN SCHEMA ACME.BRAIN TO ROLE ACME_CS_LEAD;
GRANT SELECT, INSERT ON ALL TABLES IN SCHEMA ACME.BRAIN TO ROLE ACME_CSM_EU;
GRANT UPDATE ON TABLE ACME.BRAIN.RISK_ALERTS TO ROLE ACME_CS_LEAD;

-- Let the current (hackathon) user switch between personas.
SET me = CURRENT_USER();
GRANT ROLE ACME_CS_LEAD TO USER IDENTIFIER($me);
GRANT ROLE ACME_CSM_EU  TO USER IDENTIFIER($me);

-- Proof: the same query under two roles.
USE ROLE ACME_CS_LEAD; SELECT REGION, COUNT(*) AS accounts FROM ACME.PULSE.WORKSPACES GROUP BY 1;
USE ROLE ACME_CSM_EU;  SELECT REGION, COUNT(*) AS accounts FROM ACME.PULSE.WORKSPACES GROUP BY 1;
USE ROLE ACCOUNTADMIN;
