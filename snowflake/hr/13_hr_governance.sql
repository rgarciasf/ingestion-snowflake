-- Which role may see which team.
CREATE OR REPLACE TABLE ACME.GOVERNANCE.TEAM_ENTITLEMENTS (ROLE_NAME STRING, TEAM STRING);
INSERT INTO ACME.GOVERNANCE.TEAM_ENTITLEMENTS
  SELECT 'ACME_HRBP', TEAM FROM ACME.PEOPLE.TEAMS
  UNION ALL SELECT 'ACME_MGR_DATA_INFRA', 'Data Infra';

CREATE OR REPLACE ROW ACCESS POLICY ACME.GOVERNANCE.TEAM_POLICY
  AS (team_name STRING) RETURNS BOOLEAN ->
    IS_ROLE_IN_SESSION('ACCOUNTADMIN')
    OR EXISTS (SELECT 1 FROM ACME.GOVERNANCE.TEAM_ENTITLEMENTS e WHERE e.TEAM = team_name AND IS_ROLE_IN_SESSION(e.ROLE_NAME))
  COMMENT = 'People data is visible only to roles entitled to that team';

ALTER TABLE ACME.PEOPLE.EMPLOYEES         ADD ROW ACCESS POLICY ACME.GOVERNANCE.TEAM_POLICY ON (TEAM);
ALTER TABLE ACME.PEOPLE.WORKLOAD_WEEKLY   ADD ROW ACCESS POLICY ACME.GOVERNANCE.TEAM_POLICY ON (TEAM);
ALTER TABLE ACME.PEOPLE.SURVEY_RESPONSES  ADD ROW ACCESS POLICY ACME.GOVERNANCE.TEAM_POLICY ON (TEAM);
ALTER TABLE ACME.PEOPLE.SURVEY_TEAM_SCORES ADD ROW ACCESS POLICY ACME.GOVERNANCE.TEAM_POLICY ON (TEAM);
ALTER TABLE ACME.PEOPLE.REVIEWS          ADD ROW ACCESS POLICY ACME.GOVERNANCE.TEAM_POLICY ON (TEAM);
ALTER TABLE ACME.PEOPLE.REVIEW_RATINGS   ADD ROW ACCESS POLICY ACME.GOVERNANCE.TEAM_POLICY ON (TEAM);
ALTER TABLE ACME.PEOPLE.GOALS            ADD ROW ACCESS POLICY ACME.GOVERNANCE.TEAM_POLICY ON (TEAM);
ALTER TABLE ACME.PEOPLE.FEEDBACK         ADD ROW ACCESS POLICY ACME.GOVERNANCE.TEAM_POLICY ON (TEAM);
ALTER TABLE ACME.BRAIN.PEOPLE_COMMITMENTS ADD ROW ACCESS POLICY ACME.GOVERNANCE.TEAM_POLICY ON (TEAM);
ALTER TABLE ACME.BRAIN.PEOPLE_ACTIONS     ADD ROW ACCESS POLICY ACME.GOVERNANCE.TEAM_POLICY ON (TEAM);

-- Salaries: only HR Business Partners see them; everyone else gets NULL.
CREATE OR REPLACE MASKING POLICY ACME.GOVERNANCE.SALARY_MASK AS (v NUMBER) RETURNS NUMBER ->
  CASE WHEN IS_ROLE_IN_SESSION('ACME_HRBP') OR IS_ROLE_IN_SESSION('ACCOUNTADMIN') THEN v ELSE NULL END
  COMMENT = 'Base salary visible to HR Business Partners only';
ALTER TABLE ACME.PEOPLE.EMPLOYEES MODIFY COLUMN SALARY_USD SET MASKING POLICY ACME.GOVERNANCE.SALARY_MASK;

-- Anonymous survey: aggregate-only, minimum group size 5, for every persona.
CREATE AGGREGATION POLICY IF NOT EXISTS ACME.GOVERNANCE.SURVEY_MIN_GROUP
  AS () RETURNS AGGREGATION_CONSTRAINT ->
    CASE WHEN IS_ROLE_IN_SESSION('ACCOUNTADMIN') THEN NO_AGGREGATION_CONSTRAINT()
         ELSE AGGREGATION_CONSTRAINT(MIN_GROUP_SIZE => 5) END
  COMMENT = 'Survey answers can only be read in aggregate, in groups of 5 or more';
ALTER TABLE ACME.PEOPLE.SURVEY_RESPONSES SET AGGREGATION POLICY ACME.GOVERNANCE.SURVEY_MIN_GROUP FORCE;

-- Documents: HR notes (access = hr) for HRBPs only; manager-only documents for managers and HRBPs.
ALTER ROW ACCESS POLICY ACME.GOVERNANCE.DOC_ACCESS_POLICY SET BODY ->
  access = 'all'
  OR IS_ROLE_IN_SESSION('ACCOUNTADMIN')
  OR (access = 'managers' AND (IS_ROLE_IN_SESSION('ACME_CS_LEAD') OR IS_ROLE_IN_SESSION('ACME_HRBP') OR IS_ROLE_IN_SESSION('ACME_MGR_DATA_INFRA')))
  OR (access = 'hr' AND IS_ROLE_IN_SESSION('ACME_HRBP'));

