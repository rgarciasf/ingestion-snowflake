-- Proof: the Data Infra review as the manager (own team only, leave types masked).
USE ROLE ACCOUNTADMIN;
SELECT EMPLOYEE, LEAVE_TYPE, START_DATE, END_DATE, WORKING_DAYS, STATUS, NOTICE_OK, ONCALL_CLASH, TEAMMATES_OFF_PENDING, PCT_TEAM_OFF_IF_ALL_APPROVED, COMP_DAYS_OWED
FROM ACME.PEOPLE.TIME_OFF_REVIEW WHERE TEAM = 'Data Infra' AND STATUS = 'pending' ORDER BY START_DATE;
