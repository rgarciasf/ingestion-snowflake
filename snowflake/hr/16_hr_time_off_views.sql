-- HR version · 16_hr_time_off_views.sql: the checks behind time-off approvals, the decisions table,
-- and governance (team row access + masking of sick/parental leave for non-HRBP roles).

USE ROLE ACCOUNTADMIN;
USE WAREHOUSE ACME_WH;

-- ---------------------------------------------------------------- decisions written by the agent (after approval)
CREATE TABLE IF NOT EXISTS ACME.BRAIN.TIME_OFF_DECISIONS (
  DECISION_ID     STRING DEFAULT UUID_STRING(),
  CREATED_AT      TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
  CREATED_BY_ROLE STRING DEFAULT CURRENT_ROLE(),
  REQUEST_ID      NUMBER,
  EMPLOYEE_ID     NUMBER,
  TEAM            STRING,
  DECISION        STRING COMMENT 'approve, approve_with_swap, decline, needs_hr',
  REASON          STRING,
  CONDITIONS      STRING COMMENT 'e.g. swap on-call week with <name>',
  APPROVED_BY     STRING
) COMMENT = 'Time-off decisions drafted by the agent and approved by the manager/HRBP. The HR Portal remains the system of record.';

-- ---------------------------------------------------------------- per-request review: every check the policy asks for
CREATE OR REPLACE VIEW ACME.PEOPLE.TIME_OFF_REVIEW COPY GRANTS
  COMMENT = 'One row per time-off request with policy and coverage checks (as of 2026-10-22)'
AS
WITH team_size AS (
  SELECT TEAM, COUNT_IF(STATUS = 'active') AS headcount FROM ACME.PEOPLE.EMPLOYEES GROUP BY TEAM
),
overlap AS (   -- other teammates off (approved or pending) on overlapping dates
  SELECT r.REQUEST_ID,
    COUNT(DISTINCT IFF(o.STATUS = 'approved', o.EMPLOYEE_ID, NULL)) AS others_off_approved,
    COUNT(DISTINCT IFF(o.STATUS = 'pending', o.EMPLOYEE_ID, NULL)) AS others_off_pending
  FROM ACME.PEOPLE.TIME_OFF_REQUESTS r
  LEFT JOIN ACME.PEOPLE.TIME_OFF_REQUESTS o
    ON o.TEAM = r.TEAM AND o.EMPLOYEE_ID <> r.EMPLOYEE_ID AND o.STATUS IN ('approved', 'pending')
   AND o.START_DATE <= r.END_DATE AND o.END_DATE >= r.START_DATE
  GROUP BY r.REQUEST_ID
),
oncall AS (    -- does the request overlap the person's own pager week?
  SELECT r.REQUEST_ID,
    MIN(s.WEEK_START) AS oncall_week,
    MAX(IFF(s.PRIMARY_ID = r.EMPLOYEE_ID, 'primary', 'secondary')) AS oncall_role
  FROM ACME.PEOPLE.TIME_OFF_REQUESTS r
  JOIN ACME.PEOPLE.ONCALL_SCHEDULE s
    ON s.TEAM = r.TEAM AND (s.PRIMARY_ID = r.EMPLOYEE_ID OR s.SECONDARY_ID = r.EMPLOYEE_ID)
   AND s.WEEK_START <= r.END_DATE AND DATEADD(day, 6, s.WEEK_START) >= r.START_DATE
  GROUP BY r.REQUEST_ID
),
pto AS (
  SELECT EMPLOYEE_ID, SUM(PTO_DAYS) AS pto_taken_since_apr FROM ACME.PEOPLE.WORKLOAD_WEEKLY GROUP BY EMPLOYEE_ID
),
booked AS (    -- approved time off still to come in 2026
  SELECT EMPLOYEE_ID, SUM(WORKING_DAYS) AS approved_upcoming_days
  FROM ACME.PEOPLE.TIME_OFF_REQUESTS WHERE STATUS = 'approved' AND START_DATE > '2026-10-22' AND START_DATE < '2027-01-01'
  GROUP BY EMPLOYEE_ID
),
comp AS (
  SELECT EMPLOYEE_ID, SUM(DAYS_OWED) AS comp_days_owed, MIN(TAKE_BY) AS comp_take_by FROM ACME.PEOPLE.COMP_DAYS_OWED GROUP BY EMPLOYEE_ID
)
SELECT
  r.REQUEST_ID, r.EMPLOYEE_ID, e.NAME AS EMPLOYEE, r.TEAM, e.LEVEL,
  r.LEAVE_TYPE, r.START_DATE, r.END_DATE, r.WORKING_DAYS, r.STATUS, r.REQUESTED_AT, r.NOTICE_DAYS,
  (r.WORKING_DAYS < 3 OR r.NOTICE_DAYS >= 14 OR r.LEAVE_TYPE IN ('sick', 'leave')) AS NOTICE_OK,
  oc.oncall_role AS ONCALL_CLASH, oc.oncall_week AS ONCALL_WEEK,
  ts.headcount AS TEAM_HEADCOUNT,
  ov.others_off_approved AS TEAMMATES_OFF_APPROVED,
  ov.others_off_pending AS TEAMMATES_OFF_PENDING,
  ROUND(100 * (ov.others_off_approved + ov.others_off_pending + 1) / NULLIF(ts.headcount, 0)) AS PCT_TEAM_OFF_IF_ALL_APPROVED,
  COALESCE(p.pto_taken_since_apr, 0) AS PTO_TAKEN_SINCE_APR,
  COALESCE(b.approved_upcoming_days, 0) AS APPROVED_UPCOMING_DAYS,
  COALESCE(c.comp_days_owed, 0) AS COMP_DAYS_OWED, c.comp_take_by AS COMP_TAKE_BY
FROM ACME.PEOPLE.TIME_OFF_REQUESTS r
JOIN ACME.PEOPLE.EMPLOYEES e ON e.EMPLOYEE_ID = r.EMPLOYEE_ID
JOIN team_size ts ON ts.TEAM = r.TEAM
LEFT JOIN overlap ov ON ov.REQUEST_ID = r.REQUEST_ID
LEFT JOIN oncall oc ON oc.REQUEST_ID = r.REQUEST_ID
LEFT JOIN pto p ON p.EMPLOYEE_ID = r.EMPLOYEE_ID
LEFT JOIN booked b ON b.EMPLOYEE_ID = r.EMPLOYEE_ID
LEFT JOIN comp c ON c.EMPLOYEE_ID = r.EMPLOYEE_ID;

-- ---------------------------------------------------------------- weekly coverage per team (Nov - Dec)
CREATE OR REPLACE VIEW ACME.PEOPLE.TEAM_COVERAGE_WEEKLY COPY GRANTS
  COMMENT = 'Per team and week: people off (approved / pending) and the share of the team out if everything pending is approved'
AS
WITH weeks AS (
  SELECT DATEADD(week, ROW_NUMBER() OVER (ORDER BY SEQ4()) - 1, '2026-11-02'::DATE) AS wk FROM TABLE(GENERATOR(ROWCOUNT => 9))
),
team_size AS (
  SELECT TEAM, COUNT_IF(STATUS = 'active') AS headcount FROM ACME.PEOPLE.EMPLOYEES GROUP BY TEAM
)
SELECT ts.TEAM, w.wk AS WEEK_START, ts.headcount AS HEADCOUNT,
  COUNT(DISTINCT IFF(r.STATUS = 'approved', r.EMPLOYEE_ID, NULL)) AS OFF_APPROVED,
  COUNT(DISTINCT IFF(r.STATUS = 'pending', r.EMPLOYEE_ID, NULL)) AS OFF_PENDING,
  ROUND(100 * COUNT(DISTINCT r.EMPLOYEE_ID) / NULLIF(ts.headcount, 0)) AS PCT_OFF_IF_ALL_APPROVED
FROM team_size ts
CROSS JOIN weeks w
LEFT JOIN ACME.PEOPLE.TIME_OFF_REQUESTS r
  ON r.TEAM = ts.TEAM AND r.STATUS IN ('approved', 'pending')
 AND r.START_DATE <= DATEADD(day, 4, w.wk) AND r.END_DATE >= w.wk
GROUP BY ts.TEAM, w.wk, ts.headcount;

-- ---------------------------------------------------------------- governance
ALTER TABLE IF EXISTS ACME.PEOPLE.TIME_OFF_REQUESTS DROP ALL ROW ACCESS POLICIES;
ALTER TABLE IF EXISTS ACME.PEOPLE.ONCALL_SCHEDULE   DROP ALL ROW ACCESS POLICIES;
ALTER TABLE IF EXISTS ACME.PEOPLE.COMP_DAYS_OWED    DROP ALL ROW ACCESS POLICIES;
ALTER TABLE IF EXISTS ACME.BRAIN.TIME_OFF_DECISIONS DROP ALL ROW ACCESS POLICIES;
ALTER TABLE ACME.PEOPLE.TIME_OFF_REQUESTS MODIFY COLUMN LEAVE_TYPE UNSET MASKING POLICY;

ALTER TABLE ACME.PEOPLE.TIME_OFF_REQUESTS ADD ROW ACCESS POLICY ACME.GOVERNANCE.TEAM_POLICY ON (TEAM);
ALTER TABLE ACME.PEOPLE.ONCALL_SCHEDULE   ADD ROW ACCESS POLICY ACME.GOVERNANCE.TEAM_POLICY ON (TEAM);
ALTER TABLE ACME.PEOPLE.COMP_DAYS_OWED    ADD ROW ACCESS POLICY ACME.GOVERNANCE.TEAM_POLICY ON (TEAM);
ALTER TABLE ACME.BRAIN.TIME_OFF_DECISIONS ADD ROW ACCESS POLICY ACME.GOVERNANCE.TEAM_POLICY ON (TEAM);

-- Medical and family leave is private: managers see "leave", HR Business Partners see the type.
CREATE MASKING POLICY IF NOT EXISTS ACME.GOVERNANCE.LEAVE_TYPE_MASK AS (v STRING) RETURNS STRING ->
  CASE WHEN IS_ROLE_IN_SESSION('ACME_HRBP') OR IS_ROLE_IN_SESSION('ACCOUNTADMIN') THEN v
       WHEN v IN ('sick', 'parental') THEN 'leave' ELSE v END
  COMMENT = 'Sick and parental leave types visible to HR Business Partners only';
ALTER TABLE ACME.PEOPLE.TIME_OFF_REQUESTS MODIFY COLUMN LEAVE_TYPE SET MASKING POLICY ACME.GOVERNANCE.LEAVE_TYPE_MASK;

