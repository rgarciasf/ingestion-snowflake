-- HR version · 17_hr_performance_views.sql: performance-review analytics for calibration and follow-up.
-- Team-level only, groups of 5+ (smaller groups are left out). Row access follows TEAM_POLICY on the base tables.

USE ROLE ACCOUNTADMIN;
USE WAREHOUSE ACME_WH;

-- Per team and cycle: completion, manager rating distribution, self vs manager gap.
CREATE OR REPLACE VIEW ACME.PEOPLE.PERFORMANCE_SUMMARY COPY GRANTS
  COMMENT = 'Per team and review cycle (2025-H1, 2025-H2, 2026-H1): review completion, manager rating distribution, average self and manager rating, self-minus-manager gap. Only groups of 5+ reviewed people.'
AS
WITH pairs AS (
  SELECT m.TEAM, m.CYCLE, m.SUBJECT_ID,
    m.STATUS AS mgr_status, m.OVERALL_RATING AS mgr_rating,
    s.STATUS AS self_status, s.OVERALL_RATING AS self_rating
  FROM ACME.PEOPLE.REVIEWS m
  LEFT JOIN ACME.PEOPLE.REVIEWS s
    ON s.SUBJECT_ID = m.SUBJECT_ID AND s.CYCLE = m.CYCLE AND s.REVIEW_TYPE = 'SELF_ASSESSMENT'
  WHERE m.REVIEW_TYPE = 'MANAGER_REVIEW'
)
SELECT
  TEAM, CYCLE,
  COUNT(*) AS PEOPLE_REVIEWED,
  ROUND(100 * COUNT_IF(mgr_status = 'SUBMITTED') / COUNT(*)) AS MANAGER_REVIEW_COMPLETION_PCT,
  ROUND(100 * COUNT_IF(self_status = 'SUBMITTED') / COUNT(*)) AS SELF_REVIEW_COMPLETION_PCT,
  ROUND(AVG(mgr_rating), 2) AS AVG_MANAGER_RATING,
  ROUND(AVG(self_rating), 2) AS AVG_SELF_RATING,
  ROUND(AVG(IFF(mgr_rating IS NOT NULL AND self_rating IS NOT NULL, self_rating - mgr_rating, NULL)), 2) AS AVG_SELF_MINUS_MANAGER,
  ROUND(100 * COUNT_IF(mgr_rating <= 2) / NULLIF(COUNT(mgr_rating), 0)) AS PCT_RATED_1_2,
  ROUND(100 * COUNT_IF(mgr_rating = 3) / NULLIF(COUNT(mgr_rating), 0)) AS PCT_RATED_3,
  ROUND(100 * COUNT_IF(mgr_rating = 4) / NULLIF(COUNT(mgr_rating), 0)) AS PCT_RATED_4,
  ROUND(100 * COUNT_IF(mgr_rating = 5) / NULLIF(COUNT(mgr_rating), 0)) AS PCT_RATED_5
FROM pairs
GROUP BY TEAM, CYCLE
HAVING COUNT(mgr_rating) >= 5;

-- Per team and competency (latest completed cycle and the one before), from submitted manager reviews.
CREATE OR REPLACE VIEW ACME.PEOPLE.PERFORMANCE_COMPETENCIES COPY GRANTS
  COMMENT = 'Average manager rating per team and competency for 2025-H2 and 2026-H1. Only groups of 5+ rated people.'
AS
SELECT TEAM, COMPETENCY,
  ROUND(AVG(IFF(CYCLE = '2026-H1', RATING, NULL)), 2) AS AVG_2026H1,
  ROUND(AVG(IFF(CYCLE = '2025-H2', RATING, NULL)), 2) AS AVG_2025H2,
  COUNT(DISTINCT IFF(CYCLE = '2026-H1', SUBJECT_ID, NULL)) AS PEOPLE_2026H1
FROM ACME.PEOPLE.REVIEW_RATINGS
WHERE CYCLE IN ('2025-H2', '2026-H1')
GROUP BY TEAM, COMPETENCY
HAVING COUNT(DISTINCT IFF(CYCLE = '2026-H1', SUBJECT_ID, NULL)) >= 5;

GRANT SELECT ON VIEW ACME.PEOPLE.PERFORMANCE_SUMMARY TO ROLE ACME_HRBP;
GRANT SELECT ON VIEW ACME.PEOPLE.PERFORMANCE_SUMMARY TO ROLE ACME_MGR_DATA_INFRA;
GRANT SELECT ON VIEW ACME.PEOPLE.PERFORMANCE_COMPETENCIES TO ROLE ACME_HRBP;
GRANT SELECT ON VIEW ACME.PEOPLE.PERFORMANCE_COMPETENCIES TO ROLE ACME_MGR_DATA_INFRA;

SELECT TEAM, CYCLE, PEOPLE_REVIEWED, MANAGER_REVIEW_COMPLETION_PCT, AVG_MANAGER_RATING, AVG_SELF_MINUS_MANAGER, PCT_RATED_5
FROM ACME.PEOPLE.PERFORMANCE_SUMMARY WHERE CYCLE = '2026-H1' ORDER BY AVG_MANAGER_RATING DESC;
